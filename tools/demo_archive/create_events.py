def main():
    rows = []
    per_age = {}
    for line in STORIES.splitlines():
        age, title, category, place, narrative, reflection = line.split('|')
        age = int(age)
        slot = per_age.get(age, 0)
        per_age[age] = slot + 1
        rows.append({'age': age, 'year': 1990 + age, 'month': [3, 7, 11][slot], 'title': title, 'category': category, 'place': place, 'narrative': narrative.replace('报名', '報名'), 'reflection': reflection})
    assert len(rows) == 50 and set(per_age) == set(range(16, 36))
    target = Path(__file__).with_name('events.json')
    target.write_text(json.dumps(rows, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'{target}: {len(rows)} records')


if __name__ == '__main__':
    main()
